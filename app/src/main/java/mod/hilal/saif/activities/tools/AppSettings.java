        LibraryCategoryView generalCategory = new LibraryCategoryView(this);
        generalCategory.setTitle(getString(R.string.settings_general));
        preferences.add(generalCategory);

        generalCategory.addLibraryItem(createPreference(R.drawable.ic_mtrl_settings_applications, getString(R.string.settings_app_settings), getString(R.string.settings_app_settings_desc), new ActivityLauncher(new Intent(getApplicationContext(), ConfigActivity.class))), true);
