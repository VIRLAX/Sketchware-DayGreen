        managersCategory.addLibraryItem(createPreference(R.drawable.ic_mtrl_pull_down, getString(R.string.settings_block_selector_manager), getString(R.string.settings_block_selector_manager_desc), openSettingsActivity(SettingsActivity.BLOCK_SELECTOR_MANAGER_FRAGMENT)), true);
        managersCategory.addLibraryItem(createPreference(R.drawable.ic_mtrl_component, getString(R.string.settings_component_manager), getString(R.string.settings_component_manager_desc), new ActivityLauncher(new Intent(getApplicationContext(), ManageCustomComponentActivity.class))), true);
        managersCategory.addLibraryItem(createPreference(R.drawable.ic_mtrl_list, getString(R.string.settings_event_manager), getString(R.string.settings_event_manager_desc), openSettingsActivity(SettingsActivity.EVENTS_MANAGER_FRAGMENT)), true);
        managersCategory.addLibraryItem(createPreference(R.drawable.ic_mtrl_box, getString(R.string.settings_local_library_manager), getString(R.string.settings_local_library_manager_desc), new ActivityLauncher(new Intent(getApplicationContext(), ManageLocalLibraryActivity.class), new Pair<>("sc_id", "system"))), true);
